package refdoc

import (
	"cmp"
	"encoding/json"
	"fmt"
	"slices"
	"strings"
)

// The pages Render returns, by file name.
const (
	IndexFile         = "README.md"
	SettingsFile      = "settings.md"
	BindingsFile      = "bindings.md"
	StandardVerbsFile = "standard-verbs.md"
)

// Topics are the pages by the topic docs.open names them with, in the
// order the index lists them.
var Topics = []struct{ Topic, File string }{
	{"index", IndexFile},
	{"settings", SettingsFile},
	{"bindings", BindingsFile},
	{"standard-verbs", StandardVerbsFile},
}

// TopicFile is the page of a topic, "" for an unknown one.
func TopicFile(topic string) string {
	for _, t := range Topics {
		if t.Topic == topic {
			return t.File
		}
	}
	return ""
}

// Options are what Render needs beside the model: the stamp the header
// names, whether to add the user's "yours:" lines, and the commands the
// header names to regenerate and to check the pages.
type Options struct {
	Stamp      Stamp
	ShowConfig bool
	// Regenerate is the command that writes the pages again
	// ("make reference"); Check the one that fails when they are stale.
	Regenerate string
	Check      string
}

// headerMark starts every generated page; Body and HeaderFingerprint find
// the header by it.
const headerMark = "<!-- generated by ochazuke refdoc; do not edit."

// Render draws the model as Markdown pages, by file name: README.md (the
// index), settings.md, bindings.md and standard-verbs.md. Each starts with the header block
// (Header). With ShowConfig the user's values and rows are added as
// "yours:" lines; without it nothing in the text depends on the user's
// configuration.
func Render(m Model, opts Options) map[string]string {
	header := Header(m, opts)
	return map[string]string{
		IndexFile:         header + renderIndex(m, opts),
		SettingsFile:      header + renderSettings(m, opts),
		BindingsFile:      header + renderBindings(m, opts),
		StandardVerbsFile: header + renderStandardVerbs(m, opts),
	}
}

// Header is the block every page starts with, ending in a blank line: that
// it is generated and must not be edited, the tool, commit, version,
// ochazuke version, commit date and catalog fingerprint, and the command
// that checks it.
func Header(m Model, opts Options) string {
	s := opts.Stamp
	var b strings.Builder
	b.WriteString(headerMark)
	if opts.Regenerate != "" {
		b.WriteString(" Regenerate: " + opts.Regenerate)
	}
	b.WriteString(" -->\n")
	b.WriteString("> **Generated reference. Do not edit.**\n")
	parts := []string{cmp.Or(s.Tool, "unknown tool") + " " + code(s.ShortCommit())}
	if s.Version != "" {
		parts = append(parts, s.Version)
	}
	if s.Ochazuke != "" {
		parts = append(parts, "ochazuke "+s.Ochazuke)
	}
	if s.Date != "" {
		parts = append(parts, s.Date)
	}
	parts = append(parts, "catalog "+code(m.Fingerprint()))
	b.WriteString("> " + strings.Join(parts, " · ") + "\n")
	if opts.Check != "" {
		b.WriteString("> " + code(opts.Check) + " fails when this page no longer matches the catalog.\n")
	}
	b.WriteString("\n")
	return b.String()
}

// Body is a page without its header block (the text after the header's
// blank line); a page without a header is all body.
func Body(page string) string {
	if !strings.HasPrefix(page, headerMark) {
		return page
	}
	if _, body, ok := strings.Cut(page, "\n\n"); ok {
		return body
	}
	return ""
}

// HeaderFingerprint is the catalog fingerprint a page's header names, ""
// when it has none.
func HeaderFingerprint(page string) string {
	if !strings.HasPrefix(page, headerMark) {
		return ""
	}
	head, _, _ := strings.Cut(page, "\n\n")
	_, rest, ok := strings.Cut(head, "catalog `")
	if !ok {
		return ""
	}
	fp, _, _ := strings.Cut(rest, "`")
	return fp
}

// rowCounts are the default rows and the tables that have any (a table
// only the user's file has rows in is not counted).
func rowCounts(m Model) (rows, tables int) {
	for _, g := range m.Bindings {
		if len(g.Rows) > 0 {
			rows, tables = rows+len(g.Rows), tables+1
		}
	}
	return rows, tables
}

func renderIndex(m Model, opts Options) string {
	tool := cmp.Or(opts.Stamp.Tool, "this tool")
	rows, tables := rowCounts(m)
	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	line("# %s reference", tool)
	line("")
	line("Generated from %s's catalog: every declared setting with its default and every default key row, without a user's configuration. The fingerprint in the header is the match key: the running binary shows its own in the docs viewer (`:docs open index`), and equal fingerprints mean these pages describe that build exactly.", tool)
	line("")
	line("| Topic | Page | What it holds |")
	line("|---|---|---|")
	line("| `settings` | [%s](%s) | %d settings: name, type, default, allowed values, section, who declares it, description |", SettingsFile, SettingsFile, len(m.Settings))
	line("| `bindings` | [%s](%s) | %d default key rows in %d tables, by noun and mode |", BindingsFile, BindingsFile, rows, tables)
	line("| `standard-verbs` | [%s](%s) | the %d standard verbs and what each needs; %d nouns with props: kind, props, verbs |", StandardVerbsFile, StandardVerbsFile, len(m.StandardVerbs), len(m.Nouns))
	line("")
	line("In the app, `docs open TOPIC` (`:help TOPIC`, `:h TOPIC`) shows a page with the user's own values and rows marked `yours:` (setting `docs.show-config`).")
	return b.String()
}

// sectionTitle names a settings section; "" is General.
func sectionTitle(section string) string { return cmp.Or(section, "General") }

func renderSettings(m Model, opts Options) string {
	tool := cmp.Or(opts.Stamp.Tool, "the application")
	settings := slices.Clone(m.Settings)
	slices.SortStableFunc(settings, func(a, b Setting) int {
		// General ("") first, then the sections by name.
		return cmp.Or(cmp.Compare(a.Section, b.Section), cmp.Compare(a.Name, b.Name))
	})
	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	line("# Settings")
	line("")
	line("%d settings, by section (the Settings page's tabs) then name. Change one with `:set NAME=VALUE`, `settings set NAME VALUE` or the Settings page; the values live in settings.json.", len(settings))
	section := "\x00"
	for _, s := range settings {
		if s.Section != section {
			section = s.Section
			line("")
			line("## %s", sectionTitle(section))
		}
		line("")
		line(`<a id="setting-%s"></a>`, s.Name)
		line("### %s", code(s.Name))
		line("")
		meta := []string{s.Type, "default " + code(formatValue(s.Default))}
		if len(s.Enum) > 0 {
			choices := make([]string, len(s.Enum))
			for i, v := range s.Enum {
				choices[i] = code(v)
			}
			meta = append(meta, "choices "+strings.Join(choices, ", "))
		}
		meta = append(meta, "section "+sectionTitle(s.Section))
		if s.Framework {
			meta = append(meta, "declared by ochazuke")
		} else {
			meta = append(meta, "declared by "+tool)
		}
		line("%s", strings.Join(meta, " · "))
		if s.Description != "" {
			line("")
			line("%s", s.Description)
		}
		if opts.ShowConfig && s.Yours != nil {
			line("")
			line("> yours: %s (%s)", code(formatValue(s.Yours)), cmp.Or(s.YoursFrom, "settings.json"))
		}
	}
	return b.String()
}

func renderBindings(m Model, opts Options) string {
	rows, tables := rowCounts(m)
	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	line("# Default key bindings")
	line("")
	line("%d rows in %d tables. A table is a noun's mode (`noun/mode`; a noun alone is its any-mode table) or an instance's. These are the defaults, without a user's bindings.json; a row in bindings.json with the same table, keys and guard replaces one, and `\"request\": null` unbinds it. A key may repeat: the first row whose action is available answers.", rows, tables)
	for _, g := range m.Bindings {
		if len(g.Rows) == 0 && !(opts.ShowConfig && len(g.Yours) > 0) {
			continue
		}
		line("")
		line(`<a id="bindings-%s"></a>`, anchor(g.Context))
		line("## %s", code(g.Context))
		if g.Extends != "" {
			line("")
			line("Extends %s: its rows answer here too.", code(g.Extends))
		}
		line("")
		if len(g.Rows) == 0 {
			line("No default rows.")
		} else {
			line("| Keys | Action | Args | When | Hint |")
			line("|---|---|---|---|---|")
			for _, r := range g.Rows {
				args := r.Args
				if r.From != "" {
					args = strings.TrimSpace(args + " from " + r.From)
				}
				if r.Flags != "" {
					args = strings.TrimSpace(args + " " + r.Flags)
				}
				hint := r.Hint
				if r.Hidden {
					hint = strings.TrimSpace(hint + " (hidden)")
				}
				line("| %s | %s | %s | %s | %s |", cell(code(r.Keys)), cell(code(r.Action)), cell(codeOrEmpty(args)), cell(codeOrEmpty(r.When)), cell(hint))
			}
		}
		if opts.ShowConfig {
			for _, y := range g.Yours {
				line("")
				line("> yours: %s", y)
			}
		}
	}
	return b.String()
}

func renderStandardVerbs(m Model, opts Options) string {
	tool := cmp.Or(opts.Stamp.Tool, "the application")
	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	line("# Standard verbs")
	line("")
	line("A noun that declares props and a store gets the standard verbs its store supports, with no handler of its own: a verb exists on a noun exactly when the row's kind fits the store and the store has what the row needs. A verb the noun declares by hand under a standard name replaces the generated one. A host mounting a tool's catalog gets the same verbs, forwarded.")
	line("")
	line("| Verb | Kinds | Needs | Subject | Many | Repeat | History | Confirm | What it does |")
	line("|---|---|---|---|---|---|---|---|---|")
	yes := func(v bool) string {
		if v {
			return "yes"
		}
		return ""
	}
	for _, v := range m.StandardVerbs {
		name := code(v.Verb)
		name += aliasList(v.Aliases)
		line("| %s | %s | %s | %s | %s | %s | %s | %s | %s |", cell(name), cell(strings.Join(v.Kinds, ", ")), cell(v.Needs), yes(v.Subject), yes(v.Many), yes(v.Repeatable), cell(v.History), cell(codeOrEmpty(v.Confirm)), cell(v.Description))
	}
	line("")
	line("The subject is the parameter named after the noun's key prop: given, it names the thing; left out, it is the thing the request acts for (the focus). Many runs once over a visual selection, as one undo step. Repeat: `.` repeats the write when it writes only simple values (enum, boolean, number, duration).")
	line("")
	line("## Nouns with props")
	if len(m.Nouns) == 0 {
		line("")
		line("No noun of %s declares props.", tool)
		return b.String()
	}
	for _, n := range m.Nouns {
		line("")
		line(`<a id="noun-%s"></a>`, anchor(n.Name))
		line("### %s", code(n.Name))
		line("")
		meta := "No store: its props are data only."
		if n.Kind != "" {
			meta = "Store kind " + code(n.Kind) + "."
		}
		var std, named []string
		for _, v := range n.Verbs {
			text := code(v.Name)
			text += aliasList(v.Aliases)
			if v.Standard != "" {
				std = append(std, text)
			} else {
				named = append(named, text)
			}
		}
		if len(std) > 0 {
			meta += " Standard verbs: " + strings.Join(std, ", ") + "."
		}
		if len(named) > 0 {
			meta += " Its own verbs: " + strings.Join(named, ", ") + "."
		}
		line("%s", meta)
		line("")
		line("| Prop | Type | Flags | Default | Description |")
		line("|---|---|---|---|---|")
		for _, p := range n.Props {
			typ := p.Type
			if p.Noun != "" {
				typ += " → " + p.Noun
			}
			if len(p.Enum) > 0 {
				typ += ": " + strings.Join(p.Enum, ", ")
			}
			var flags []string
			for _, f := range []struct {
				on   bool
				text string
			}{{p.Key, "key"}, {p.Required, "required"}, {p.ReadOnly && !p.Key, "read-only"}, {p.CreateOnly, "create-only"},
				{len(p.Aliases) > 0, "also: " + strings.Join(p.Aliases, ", ")},
				{p.Role != "", "role " + p.Role}, {p.Fallback != "", "fallback " + p.Fallback}, {p.FromFocus, "from focus"},
				{p.Secret, "secret"}, {p.Multiline, "multiline"}, {p.When != "", "when " + p.When}} {
				if f.on {
					flags = append(flags, f.text)
				}
			}
			def := ""
			if p.Default != nil {
				def = code(formatValue(p.Default))
			}
			line("| %s | %s | %s | %s | %s |", cell(code(p.Name)), cell(typ), cell(strings.Join(flags, ", ")), cell(def), cell(p.Description))
		}
	}
	return b.String()
}

// aliasList is a verb's aliases as " (`a`, `b`)", "" for none.
func aliasList(aliases []string) string {
	if len(aliases) == 0 {
		return ""
	}
	parts := make([]string, len(aliases))
	for i, a := range aliases {
		parts[i] = code(a)
	}
	return " (" + strings.Join(parts, ", ") + ")"
}

// formatValue writes a setting value: a nonempty string as is, anything
// else as JSON ("" as "", lists as arrays).
func formatValue(v any) string {
	if s, ok := v.(string); ok && s != "" {
		return s
	}
	data, err := json.Marshal(v)
	if err != nil {
		return fmt.Sprint(v)
	}
	return string(data)
}

// code is s as a Markdown code span, fenced with two backticks when it
// holds one.
func code(s string) string {
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

func codeOrEmpty(s string) string {
	if s == "" {
		return ""
	}
	return code(s)
}

// cell escapes a table cell's pipes and keeps it on one line.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

// anchor is a table context as an id: slashes and spaces become dashes.
func anchor(context string) string {
	return strings.NewReplacer("/", "-", " ", "-").Replace(context)
}
