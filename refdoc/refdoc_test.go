func TestStampShortCommit(t *testing.T) {
	for _, tc := range []struct {
		s    Stamp
		want string
	}{
		{Stamp{}, "unknown build"},
		{Stamp{Commit: "3b3bc61d528a4f0e"}, "3b3bc61d528a"},
		{Stamp{Commit: "3b3bc61", Dirty: true}, "3b3bc61+dirty"},
	} {
		if got := tc.s.ShortCommit(); got != tc.want {
			t.Errorf("%+v: %q, want %q", tc.s, got, tc.want)
		}
	}
}

// The build info gives the commit, date, dirty mark and versions; the
// linker stamps win over it.
func TestStampFromBuildInfoThenLinker(t *testing.T) {
	bi := &debug.BuildInfo{
		Main: debug.Module{Path: "example.com/mtm", Version: "v1.2.3"},
		Deps: []*debug.Module{{Path: "github.com/unixsuperhero/ochazuke", Version: "v0.50.0"}},
		Settings: []debug.BuildSetting{
			{Key: "vcs.revision", Value: "aaaaaaaaaaaaaaaa"},
			{Key: "vcs.time", Value: "2026-10-29T12:00:00Z"},
			{Key: "vcs.modified", Value: "true"},
		},
	}
	s := fromBuildInfo("mtm", bi)
	if s != (Stamp{Tool: "mtm", Version: "v1.2.3", Commit: "aaaaaaaaaaaaaaaa", Dirty: true, Date: "2026-10-29", Ochazuke: "v0.50.0"}) {
		t.Fatalf("from build info: %+v", s)
	}
	defer func(c, v, d, x string) { Commit, Version, Date, Dirty = c, v, d, x }(Commit, Version, Date, Dirty)
	Commit, Version, Date, Dirty = "bbbb", "v9", "2026-10-30", ""
	s = withLinkerStamps(s)
	if s.Commit != "bbbb" || s.Dirty || s.Date != "2026-10-30" || s.Version != "v9" || s.Ochazuke != "v0.50.0" {
		t.Fatalf("linker stamps: %+v", s)
	}
	// A replaced ochazuke reports its replacement's version; ochazuke's own
	// build its main version.
	bi.Deps[0].Replace = &debug.Module{Path: "../ochazuke", Version: "v0.51.0"}
	if got := ochazukeOf(bi); got != "v0.51.0" {
		t.Errorf("replaced: %q", got)
	}
	if got := ochazukeOf(&debug.BuildInfo{Main: debug.Module{Path: "github.com/unixsuperhero/ochazuke", Version: "(devel)"}}); got != "" {
		t.Errorf("devel main: %q", got)
	}
}

// Every page starts with the header block: generated, do not edit, the
// stamp's fields and the fingerprint; Body and HeaderFingerprint read it.
func TestRenderHeader(t *testing.T) {
	m := sample()
	stamp := Stamp{Tool: "ochazuke", Commit: "3b3bc61d528a4f0e", Version: "v0.50.0", Ochazuke: "v0.50.0", Date: "2026-10-29"}
	pages := Render(m, Options{Stamp: stamp, Regenerate: "make reference", Check: "go test ./cmd/docgen"})
	if len(pages) != 3 {
		t.Fatalf("%d pages", len(pages))
	}
	want := "<!-- generated by ochazuke refdoc; do not edit. Regenerate: make reference -->\n" +
		"> **Generated reference. Do not edit.**\n" +
		"> ochazuke `3b3bc61d528a` · v0.50.0 · ochazuke v0.50.0 · 2026-10-29 · catalog `" + m.Fingerprint() + "`\n" +
		"> `go test ./cmd/docgen` fails when this page no longer matches the catalog.\n\n"
	for name, page := range pages {
		if !strings.HasPrefix(page, want) {
			t.Errorf("%s header:\n%s", name, page[:min(len(page), 400)])
		}
		if HeaderFingerprint(page) != m.Fingerprint() {
			t.Errorf("%s: fingerprint %q", name, HeaderFingerprint(page))
		}
		if Body(page) != strings.TrimPrefix(page, want) {
			t.Errorf("%s: Body is not the text after the header", name)
		}
	}
	if Body("# plain\n\ntext") != "# plain\n\ntext" || HeaderFingerprint("# plain") != "" {
		t.Error("a page without a header")
	}
}

// settings.md: name, type, default, choices, section, who declares it,
// description; bindings.md: a table per context, pipes escaped, hidden
// marked; yours lines only with ShowConfig, and never in the fingerprint.
func TestRenderPages(t *testing.T) {
	m := sample()
	pages := Render(m, Options{Stamp: Stamp{Tool: "mtm"}})
	settings := Body(pages[SettingsFile])
	for _, want := range []string{
		"## General\n\n<a id=\"setting-focus-display\"></a>\n### `focus-display`\n\nstring · default `off` · choices `off`, `noun`, `stack` · section General · declared by ochazuke\n\nShow where the focus is\n",
		"list · default `[\"/Volumes/\"]` · section path · declared by ochazuke",
		"boolean · default `true` · section tree · declared by mtm",
	} {
		if !strings.Contains(settings, want) {
			t.Errorf("settings.md lacks %q:\n%s", want, settings)
		}
	}
	if strings.Index(settings, "## path") > strings.Index(settings, "## tree") {
		t.Error("sections out of order")
	}
	bindings := Body(pages[BindingsFile])
	for _, want := range []string{
		"3 rows in 2 tables.",
		"## `app/normal`\n\n| Keys | Action | Args | When | Hint |\n|---|---|---|---|---|\n| `?` | `ochazuke.bindings.help` |  |  |  |\n| `\\|` | `demo.pipe` | `{\"n\":1} from count=count` |  | pipe (hidden) |\n",
		"## `app/count_pending`\n\nExtends `normal`: its rows answer here too.",
	} {
		if !strings.Contains(bindings, want) {
			t.Errorf("bindings.md lacks %q:\n%s", want, bindings)
		}
	}
	fp := m.Fingerprint()
	m.Settings[0].Yours, m.Settings[0].YoursFrom = "stack", "session"
	m.Bindings[0].Yours = []string{"`?` unbound (bindings.json)"}
	if m.Fingerprint() != fp {
		t.Error("yours lines changed the fingerprint")
	}
	// A table only the user's file has rows in.
	m.Bindings = append(m.Bindings, Group{Context: "demo/normal", Rows: []Row{}, Yours: []string{"`x` → `demo.x` (added) (bindings.json)"}})
	if m.Fingerprint() != fp {
		t.Error("a table only the user's file has changed the fingerprint")
	}
	off := Render(m, Options{Stamp: Stamp{Tool: "mtm"}})
	if Body(off[SettingsFile]) != settings || Body(off[BindingsFile]) != bindings {
		t.Error("yours data shows without ShowConfig")
	}
	on := Render(m, Options{Stamp: Stamp{Tool: "mtm"}, ShowConfig: true})
	if !strings.Contains(on[SettingsFile], "> yours: `stack` (session)") {
		t.Error("no yours line for the setting")
	}
	if !strings.Contains(on[BindingsFile], "> yours: `?` unbound (bindings.json)") || !strings.Contains(on[BindingsFile], "## `demo/normal`\n\nNo default rows.\n\n> yours: `x`") {
		t.Errorf("no yours lines for the rows:\n%s", on[BindingsFile])
	}
}

// Check: nothing when the pages match (an older header commit is fine),
// missing, extra and changed pages otherwise, with the lines that differ.
func TestCheck(t *testing.T) {
	m := sample()
	dir := t.TempDir()
	old := Options{Stamp: Stamp{Tool: "mtm", Commit: "1111111"}}
	for name, text := range Render(m, old) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	now := Options{Stamp: Stamp{Tool: "mtm", Commit: "2222222", Dirty: true}}
	if diffs, err := Check(m, now, dir); err != nil || len(diffs) != 0 {
		t.Fatalf("matching pages: %v %v", diffs, err)
	}
	changed := sample()
	changed.Settings[0].Default = "noun"
	diffs, err := Check(changed, now, dir)
	if err != nil {
		t.Fatal(err)
	}
	var settings *Diff
	for i, d := range diffs {
		if d.File == SettingsFile {
			settings = &diffs[i]
		}
	}
	if settings == nil || settings.Problem != Changed || !strings.Contains(settings.Detail, "- string · default `off`") || !strings.Contains(settings.Detail, "+ string · default `noun`") {
		t.Fatalf("a changed default: %v", diffs)
	}
	if len(diffs) != 3 {
		t.Errorf("the other pages' fingerprints: %v", diffs)
	}
	if err := os.Remove(filepath.Join(dir, BindingsFile)); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "stale.md"), []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	diffs, err = Check(m, now, dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(diffs) != 2 || diffs[0] != (Diff{File: BindingsFile, Problem: Missing}) || diffs[1] != (Diff{File: "stale.md", Problem: Extra}) {
		t.Fatalf("missing and extra: %v", diffs)
	}
	// A hand edit below the header is a change even with the fingerprint
	// intact.
	path := filepath.Join(dir, IndexFile)
	data, _ := os.ReadFile(path)
	if err := os.WriteFile(path, append(data, "edited\n"...), 0o644); err != nil {
		t.Fatal(err)
	}
	diffs, _ = Check(m, now, dir)
	if len(diffs) != 3 || diffs[0].File != IndexFile || !strings.Contains(diffs[0].Detail, "- edited") {
		t.Fatalf("a hand edit: %v", diffs)
	}
}

