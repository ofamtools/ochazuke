// Command codemap writes docs/CODEMAP.md: one entry per Go file in the root
// package, listing what each file declares and which sibling files it leans
// on. It is generated so it cannot drift; run `make codemap`.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type fileInfo struct {
	name     string
	lines    int
	purpose  string
	types    []string
	funcs    []string
	methods  map[string]int // receiver type -> count
	declared map[string]bool
	testFile string
	refs     map[string]int // other file -> ident uses
	isTest   bool
}

func main() {
	root := "."
	out := filepath.Join("docs", "CODEMAP.md")
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	if len(os.Args) > 2 {
		out = os.Args[2]
	}
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, root, func(fi os.FileInfo) bool {
		return strings.HasSuffix(fi.Name(), ".go")
	}, parser.ParseComments)
	if err != nil {
		fail(err)
	}
	files := map[string]*fileInfo{}
	astFiles := map[string]*ast.File{}
	for _, pkg := range pkgs {
		for path, f := range pkg.Files {
			name := filepath.Base(path)
			fi := &fileInfo{name: name, methods: map[string]int{}, declared: map[string]bool{}, refs: map[string]int{}}
			fi.isTest = strings.HasSuffix(name, "_test.go")
			fi.lines = fset.File(f.Pos()).LineCount()
			collect(fi, f)
			files[name] = fi
			astFiles[name] = f
		}
	}
	// owner index: declared name -> file (non-test only)
	owner := map[string]string{}
	for _, fi := range files {
		if fi.isTest {
			continue
		}
		for n := range fi.declared {
			owner[n] = fi.name
		}
	}
	for name, f := range astFiles {
		fi := files[name]
		ast.Inspect(f, func(n ast.Node) bool {
			id, ok := n.(*ast.Ident)
			if !ok {
				return true
			}
			if o, ok := owner[id.Name]; ok && o != name {
				fi.refs[o]++
			}
			return true
		})
		if fi.isTest {
			base := strings.TrimSuffix(name, "_test.go") + ".go"
			if src, ok := files[base]; ok {
				src.testFile = name
			}
		}
	}
	var names []string
	for n, fi := range files {
		if !fi.isTest {
			names = append(names, n)
		}
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "# Code map\n\n")
	fmt.Fprintf(&b, "Generated by `make codemap` (cmd/codemap). Do not edit by hand.\n\n")
	fmt.Fprintf(&b, "Root package `ochazuke` is flat: %d source files, %d test files. ", len(names), len(files)-len(names))
	fmt.Fprintf(&b, "Each entry lists what the file declares and the sibling files whose identifiers it uses most (\"leans on\"), so an agent can open two or three files instead of grepping.\n\n")
	fmt.Fprintf(&b, "## Files\n\n")
	for _, n := range names {
		fi := files[n]
		fmt.Fprintf(&b, "### %s\n\n", n)
		fmt.Fprintf(&b, "- lines: %d", fi.lines)
		if fi.testFile != "" {
			fmt.Fprintf(&b, " · tests: %s", fi.testFile)
		}
		fmt.Fprintf(&b, "\n")
		if fi.purpose != "" {
			fmt.Fprintf(&b, "- purpose: %s\n", fi.purpose)
		}
		if len(fi.types) > 0 {
			fmt.Fprintf(&b, "- types: %s\n", strings.Join(fi.types, ", "))
		}
		if len(fi.methods) > 0 {
			fmt.Fprintf(&b, "- methods: %s\n", joinCounts(fi.methods))
		}
		if len(fi.funcs) > 0 {
			fmt.Fprintf(&b, "- funcs: %s\n", strings.Join(fi.funcs, ", "))
		}
		if len(fi.refs) > 0 {
			fmt.Fprintf(&b, "- leans on: %s\n", topN(fi.refs, 4))
		}
		fmt.Fprintf(&b, "\n")
	}
	fmt.Fprintf(&b, "## Symbol owners\n\n")
	fmt.Fprintf(&b, "Exported type -> file.\n\n")
	var syms []string
	for n, o := range owner {
		if ast.IsExported(n) && isType(files[o], n) {
			syms = append(syms, fmt.Sprintf("- %s -> %s", n, o))
		}
	}
	sort.Strings(syms)
	fmt.Fprintf(&b, "%s\n", strings.Join(syms, "\n"))
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d files)\n", out, len(names))
}

func collect(fi *fileInfo, f *ast.File) {
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			if fi.purpose == "" && d.Doc != nil {
				fi.purpose = firstSentence(d.Doc.Text())
			}
			if d.Recv != nil {
				fi.methods[recvName(d.Recv)]++
			} else {
				fi.declared[d.Name.Name] = true
				if d.Name.IsExported() {
					fi.funcs = append(fi.funcs, d.Name.Name)
				}
			}
		case *ast.GenDecl:
			for _, s := range d.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					fi.declared[s.Name.Name] = true
					if fi.purpose == "" {
						if s.Doc != nil {
							fi.purpose = firstSentence(s.Doc.Text())
						} else if d.Doc != nil {
							fi.purpose = firstSentence(d.Doc.Text())
						}
					}
					if s.Name.IsExported() {
						fi.types = append(fi.types, s.Name.Name+kindSuffix(s.Type))
					}
				case *ast.ValueSpec:
					for _, n := range s.Names {
						fi.declared[n.Name] = true
					}
				}
			}
		}
	}
}

func kindSuffix(e ast.Expr) string {
	switch e.(type) {
	case *ast.StructType:
		return ""
	case *ast.InterfaceType:
		return " (iface)"
	case *ast.FuncType:
		return " (func)"
	default:
		return ""
	}
}

func recvName(r *ast.FieldList) string {
	if len(r.List) == 0 {
		return "?"
	}
	t := r.List[0].Type
	if s, ok := t.(*ast.StarExpr); ok {
		t = s.X
	}
	if ix, ok := t.(*ast.IndexExpr); ok {
		t = ix.X
	}
	if id, ok := t.(*ast.Ident); ok {
		return id.Name
	}
	return "?"
}

func isType(fi *fileInfo, n string) bool {
	for _, t := range fi.types {
		if strings.TrimSuffix(strings.TrimSuffix(t, " (iface)"), " (func)") == n {
			return true
		}
	}
	return false
}

func firstSentence(s string) string {
	s = strings.TrimSpace(strings.ReplaceAll(s, "\n", " "))
	if i := strings.Index(s, ". "); i > 0 {
		s = s[:i+1]
	}
	if len(s) > 160 {
		s = s[:157] + "..."
	}
	return s
}

func joinCounts(m map[string]int) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%s(%d)", k, m[k]))
	}
	return strings.Join(parts, ", ")
}

func topN(m map[string]int, n int) string {
	type kv struct {
		k string
		v int
	}
	var kvs []kv
	for k, v := range m {
		kvs = append(kvs, kv{k, v})
	}
	sort.Slice(kvs, func(i, j int) bool {
		if kvs[i].v != kvs[j].v {
			return kvs[i].v > kvs[j].v
		}
		return kvs[i].k < kvs[j].k
	})
	if len(kvs) > n {
		kvs = kvs[:n]
	}
	parts := make([]string, 0, len(kvs))
	for _, e := range kvs {
		parts = append(parts, fmt.Sprintf("%s(%d)", e.k, e.v))
	}
	return strings.Join(parts, ", ")
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "codemap:", err)
	os.Exit(1)
}
