// Command charmrefs writes docs/CHARM-INVENTORY.md: for every project listed in
// docs/charm-refs.txt, the Charm (charm.land, charmbracelet) modules it depends
// on, how many files import each package, its entry points, and its agent docs.
// Facts only; the judgment about what each project is good for lives in
// AGENTS.md. Run `make codemap`.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	importRe = regexp.MustCompile(`"((?:charm\.land|github\.com/charmbracelet)/[^"]+)"`)
	mainRe   = regexp.MustCompile(`(?m)^func main\(\)`)
	skipDirs = map[string]bool{".git": true, ".worktrees": true, "vendor": true, "node_modules": true, ".dev": true, ".wasm-build": true}
)

type project struct {
	dir, module string
	goFiles     int
	deps        []string
	imports     map[string]int
	mains       []string
	newProgram  []string
	docs        []string
}

func main() {
	list := filepath.Join("docs", "charm-refs.txt")
	out := filepath.Join("docs", "CHARM-INVENTORY.md")
	dirs, err := readList(list)
	if err != nil {
		fail(err)
	}
	var projects []project
	for _, d := range dirs {
		p, err := scan(d)
		if err != nil {
			fmt.Fprintf(os.Stderr, "charmrefs: %s: %v\n", d, err)
			continue
		}
		projects = append(projects, p)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Charm inventory\n\n")
	fmt.Fprintf(&b, "Generated by `make codemap` (cmd/charmrefs) from `docs/charm-refs.txt`. Do not edit by hand. ")
	fmt.Fprintf(&b, "For which project to open for which pattern, see the References section of AGENTS.md.\n\n")
	fmt.Fprintf(&b, "## Summary\n\n| project | bubbletea | lipgloss | go files | agent docs |\n|---|---|---|---|---|\n")
	for _, p := range projects {
		fmt.Fprintf(&b, "| %s | %s | %s | %d | %s |\n", filepath.Base(p.dir), dep(p, "bubbletea"), dep(p, "lipgloss"), p.goFiles, strings.Join(p.docs, ", "))
	}
	fmt.Fprintf(&b, "\n")
	for _, p := range projects {
		fmt.Fprintf(&b, "## %s\n\n", filepath.Base(p.dir))
		fmt.Fprintf(&b, "- path: %s\n- module: %s\n- go files: %d\n", p.dir, p.module, p.goFiles)
		if len(p.mains) > 0 {
			fmt.Fprintf(&b, "- entry points: %s\n", strings.Join(p.mains, ", "))
		}
		if len(p.newProgram) > 0 {
			fmt.Fprintf(&b, "- tea.NewProgram: %s\n", strings.Join(p.newProgram, ", "))
		}
		if len(p.deps) > 0 {
			fmt.Fprintf(&b, "- direct charm deps: %s\n", strings.Join(p.deps, ", "))
		}
		if len(p.imports) > 0 {
			fmt.Fprintf(&b, "- files importing each charm package:\n")
			for _, kv := range sorted(p.imports) {
				fmt.Fprintf(&b, "  - %s: %d\n", kv.k, kv.v)
			}
		}
		fmt.Fprintf(&b, "\n")
	}
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d projects)\n", out, len(projects))
}

func readList(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var dirs []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		dirs = append(dirs, line)
	}
	return dirs, sc.Err()
}

func scan(dir string) (project, error) {
	p := project{dir: dir, imports: map[string]int{}}
	mod, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return p, err
	}
	inReq := false
	for _, line := range strings.Split(string(mod), "\n") {
		line = strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(line, "module "):
			p.module = strings.TrimSpace(strings.TrimPrefix(line, "module "))
		case line == "require (":
			inReq = true
		case line == ")":
			inReq = false
		case inReq && strings.Contains(line, "charm") && !strings.Contains(line, "// indirect"):
			f := strings.Fields(line)
			if len(f) >= 2 {
				p.deps = append(p.deps, f[0]+" "+f[1])
			}
		}
	}
	for _, name := range []string{"AGENTS.md", "CLAUDE.md", "README.md", "docs"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			p.docs = append(p.docs, name)
		}
	}
	err = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			if path != dir && skipDirs[d.Name()] {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		p.goFiles++
		src, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(dir, path)
		seen := map[string]bool{}
		for _, m := range importRe.FindAllSubmatch(src, -1) {
			pkg := string(m[1])
			if !seen[pkg] {
				seen[pkg] = true
				p.imports[pkg]++
			}
		}
		if strings.HasSuffix(path, "_test.go") {
			return nil
		}
		if mainRe.Match(src) {
			p.mains = append(p.mains, rel)
		}
		if bytes.Contains(src, []byte("tea.NewProgram")) {
			p.newProgram = append(p.newProgram, rel)
		}
		return nil
	})
	sort.Strings(p.mains)
	sort.Strings(p.newProgram)
	return p, err
}

func dep(p project, name string) string {
	for _, d := range p.deps {
		if strings.Contains(d, "/"+name) {
			f := strings.Fields(d)
			if strings.Contains(f[0], "charm.land") {
				return "v2 " + f[1]
			}
			return "v1 " + f[1]
		}
	}
	if n := p.imports["charm.land/"+name+"/v2"]; n > 0 {
		return "v2 (transitive)"
	}
	return "-"
}

type kv struct {
	k string
	v int
}

func sorted(m map[string]int) []kv {
	var kvs []kv
	for k, v := range m {
		kvs = append(kvs, kv{k, v})
	}
	sort.Slice(kvs, func(i, j int) bool {
		if kvs[i].v != kvs[j].v {
			return kvs[i].v > kvs[j].v
		}
		return kvs[i].k < kvs[j].k
	})
	return kvs
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "charmrefs:", err)
	os.Exit(1)
}
